/// The English name of the language `code`, if it is one of the listed.
pub fn language_name(code: &str) -> Option<&'static str> {
    LANGUAGES
        .binary_search_by(|(listed, _)| listed.cmp(&code))
        .ok()
        .map(|ix| LANGUAGES[ix].1)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_languages_are_sorted_and_found() {
        assert!(LANGUAGES.windows(2).all(|pair| pair[0].0 < pair[1].0));
        assert_eq!(language_name("en"), Some("English"));
        assert_eq!(language_name("zh-min-nan"), Some("Min Nan Chinese"));
        assert_eq!(language_name("qqq"), None);
    }
}
